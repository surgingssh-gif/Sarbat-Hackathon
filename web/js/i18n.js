// t("key", { n: 5 }) -> text in the current language with {placeholders} filled in.
Atlas.t = function (key, vars) {
  const table = Atlas.STRINGS[Atlas.lang] || Atlas.STRINGS.en;
  let s = table[key] ?? Atlas.STRINGS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
};

// Pick the current language from a { en, pa } object.
Atlas.tr = function (obj) {
  if (!obj) return "";
  if (typeof obj === "string") return obj;
  return obj[Atlas.lang] || obj.en || "";
};

Atlas.placeName = function (geo) {
  if (!geo) return "";
  if (geo.level === "state") return Atlas.t("punjab");
  if (geo.level === "district" && Atlas.lang === "pa") return Atlas.DISTRICT_PA[geo.name] || geo.name;
  return geo.name;
};
